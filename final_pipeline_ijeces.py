def ece(y, s, bins=10):
    e_, n_ = 0., len(y); edges = np.linspace(0, 1, bins+1)
    for i in range(bins):
        m_ = (s > edges[i]) & (s <= edges[i+1])
        if m_.sum(): e_ += (m_.sum()/n_)*abs(y[m_].mean() - s[m_].mean())
    return float(e_)
